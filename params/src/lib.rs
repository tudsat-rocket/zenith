//! Core types for the parameter system.
//!
//! A parameter is addressed by a stable `u16` id (its flash storage key) and carries a raw `u32`
//! payload. Higher layers map ids to MAVLink names.

#![no_std]
#![allow(
    clippy::indexing_slicing,
    reason = "slot indices are bounded by each field's declared WIDTH"
)]

use nalgebra::Vector3;
use rapid_dialect::rapid::enums::{MavParamType, ParamMetadataFlag};
use rapid_dialect::rapid::messages::ParamMetadata;

/// The wire/storage type of a single parameter slot.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ParamType {
    F32,
    U32,
}

/// A single parameter value.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum ParamValue {
    F32(f32),
    U32(u32),
}

/// A registered and valid parameter's stable id (its flash storage key).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct ParamId(u16);

/// Describes one parameter slot: its stable id, full MAVLink name, type and what a ground station
/// shows about it.
#[derive(Debug, Clone, Copy)]
pub struct ParamDescriptor {
    pub id: ParamId,
    pub name: &'static str,
    pub ty: ParamType,
    /// One line, the first paragraph of the field's doc comment.
    pub description: &'static str,
    /// Empty if dimensionless.
    pub unit: &'static str,
    /// Smallest accepted value, the type's own if the param declares none.
    pub min: ParamValue,
    /// Largest accepted value, the type's own if the param declares none.
    pub max: ParamValue,
    /// Whether a change only takes effect on the next boot.
    pub reboot_required: bool,
}

/// The type of a single parameter slot's value.
pub trait ParamScalar: Copy {
    /// The bounds of a param that declares none.
    const MIN: Self;
    const MAX: Self;

    fn value(self) -> ParamValue;
}

/// A single struct field that maps onto one or more parameter slots.
///
/// Scalars occupy one slot; composite types (e.g. [`Vector3`]) occupy several consecutive slots.
/// Implemented for the primitive parameter types; the derive macro dispatches through this trait
/// so it never needs to understand the concrete field type.
pub trait ParameterField: Sized {
    /// Number of parameter slots this field occupies.
    const WIDTH: usize;
    /// The type of every slot (all slots of a field share one type).
    const SLOT_TYPE: ParamType;
    /// The scalar the field is built from (used to type the `default` array and the bounds).
    type Scalar: ParamScalar;

    fn get_slot(&self, index: usize) -> ParamValue;

    /// Returns false if `value` does not match [`Self::SLOT_TYPE`].
    fn set_slot(&mut self, index: usize, value: ParamValue) -> bool;

    /// Build a field value from its per-slot defaults (`slots.len() == WIDTH`).
    fn from_slots(slots: &[Self::Scalar]) -> Self;
}

/// A struct whose fields are parameters (leaf group) or parameter groups (aggregate).
/// Implementations are generated by the `macros` crate.
pub trait ParameterGroup {
    /// Total number of parameter slots in this group.
    const PARAM_COUNT: usize;

    /// The descriptor at a flat slot index, or None if out of range.
    fn descriptor(index: usize) -> Option<ParamDescriptor>
    where
        Self: Sized;

    /// The current value of the parameter with the given id, if present.
    fn get(&self, id: ParamId) -> Option<ParamValue>;

    /// Apply a value to the parameter with the given id. Returns false if the id does not belong to
    /// this group or the value type does not match.
    fn set(&mut self, id: ParamId, value: ParamValue) -> bool;
}

impl ParamType {
    /// Reconstruct a value from its raw u32 storage representation.
    pub fn decode_raw(self, raw: u32) -> ParamValue {
        match self {
            ParamType::F32 => ParamValue::F32(f32::from_bits(raw)),
            ParamType::U32 => ParamValue::U32(raw),
        }
    }

    /// Reconstruct a value from a MAVLink `param_value` field (bytewise encoding, so the raw bits
    /// arrive unchanged and nothing is lost for u32 params).
    pub fn from_mavlink(self, v: f32) -> Option<ParamValue> {
        match self {
            ParamType::F32 if !v.is_finite() => None,
            _ => Some(self.decode_raw(v.to_bits())),
        }
    }
}

impl From<ParamType> for MavParamType {
    fn from(ty: ParamType) -> Self {
        match ty {
            ParamType::F32 => MavParamType::Real32,
            ParamType::U32 => MavParamType::Uint32,
        }
    }
}

impl ParamValue {
    /// The raw u32 stored in flash (f32 bit pattern or the value itself).
    pub fn encode_raw(self) -> u32 {
        match self {
            ParamValue::F32(v) => v.to_bits(),
            ParamValue::U32(v) => v,
        }
    }

    /// The value as it goes into a MAVLink `param_value` field: the same raw u32 as storage uses,
    /// reinterpreted as a float (bytewise encoding).
    pub fn to_mavlink(self) -> f32 {
        f32::from_bits(self.encode_raw())
    }

    pub fn param_type(self) -> ParamType {
        match self {
            ParamValue::F32(_) => ParamType::F32,
            ParamValue::U32(_) => ParamType::U32,
        }
    }
}

impl ParamId {
    pub const fn new(id: u16) -> Self {
        Self(id)
    }

    pub const fn get(self) -> u16 {
        self.0
    }
}

impl ParamDescriptor {
    /// The name as a 16-byte NUL-padded MAVLink `param_id`.
    pub fn mavlink_name(&self) -> [u8; 16] {
        nul_padded(self.name)
    }

    /// Whether `value` has this param's type and lies within its bounds.
    pub fn accepts(&self, value: ParamValue) -> bool {
        match (value, self.min, self.max) {
            (ParamValue::F32(v), ParamValue::F32(min), ParamValue::F32(max)) => {
                (min..=max).contains(&v)
            }
            (ParamValue::U32(v), ParamValue::U32(min), ParamValue::U32(max)) => {
                (min..=max).contains(&v)
            }
            _ => false,
        }
    }

    /// The PARAM_METADATA describing this param, whose default value is `default`.
    pub fn metadata(&self, default: ParamValue) -> ParamMetadata {
        ParamMetadata {
            param_id: self.mavlink_name(),
            param_type: self.ty.into(),
            default_value: default.to_mavlink(),
            min_value: self.min.to_mavlink(),
            max_value: self.max.to_mavlink(),
            flags: if self.reboot_required {
                ParamMetadataFlag::REBOOT_REQUIRED
            } else {
                ParamMetadataFlag::empty()
            },
            units: nul_padded(self.unit),
            description: nul_padded(self.description),
        }
    }
}

impl ParamScalar for f32 {
    const MIN: Self = f32::NEG_INFINITY;
    const MAX: Self = f32::INFINITY;

    fn value(self) -> ParamValue {
        ParamValue::F32(self)
    }
}

impl ParamScalar for u32 {
    const MIN: Self = u32::MIN;
    const MAX: Self = u32::MAX;

    fn value(self) -> ParamValue {
        ParamValue::U32(self)
    }
}

impl ParameterField for f32 {
    const WIDTH: usize = 1;
    const SLOT_TYPE: ParamType = ParamType::F32;
    type Scalar = f32;

    fn get_slot(&self, _index: usize) -> ParamValue {
        ParamValue::F32(*self)
    }

    fn set_slot(&mut self, _index: usize, value: ParamValue) -> bool {
        if let ParamValue::F32(v) = value {
            *self = v;
            true
        } else {
            false
        }
    }

    fn from_slots(slots: &[f32]) -> Self {
        slots[0]
    }
}

